def name(f):return bytes.fromhex(f['function_hex']).decode(errors='replace')
def canonical(f):
    code=bytes.fromhex(f['code_before_hex']);out=[]
    for op in f['opcodes']:
        atom=bytes.fromhex(op['atom_hex']).decode(errors='replace')
        operand='atom:'+atom if atom else code[op['pc']+1:op['pc']+op['size']].hex()
        out.append([op['pc'],op['size'],op['before_op'],operand])
    return out
def blocks(text):
    starts=list(re.finditer(r'^\[generated bytecode for function: (.*?) \(',text,re.M));out={}
    for i,m in enumerate(starts):out.setdefault(m[1],[]).append(text[m.start():starts[i+1].start() if i+1<len(starts) else len(text)])
    return out
def instructions(block):
    out=[]
    for line in block.splitlines():
        m=re.search(r'(0x[0-9a-f]+)\s+@\s*(\d+)\s*:\s*((?:[0-9a-f]{2}\s+)+)(.+)',line)
        if m:out.append(dict(address=m[1],pc=int(m[2]),bytes=m[3].split(),instruction=re.sub(r'0x[0-9a-f]+','ADDR',m[4]).strip()))
    return out
