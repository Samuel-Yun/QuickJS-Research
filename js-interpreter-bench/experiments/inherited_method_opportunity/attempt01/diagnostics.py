def textfun(f):return bytes.fromhex(f['function_hex']).decode(errors='replace')
def canonical(f):
    code=bytes.fromhex(f['code_before_hex']);out=[]
    for op in f['opcodes']:
        name=op['before_op'];name=name.replace('_rdi','');atom=bytes.fromhex(op['atom_hex']).decode(errors='replace')
        operands=('atom:'+atom) if atom else code[op['pc']+1:op['pc']+op['size']].hex()
        out.append([op['pc'],op['size'],name,operands])
    return out
def v8_blocks(text):
    starts=list(re.finditer(r'^\[generated bytecode for function: (.*?) \(',text,re.M));out={}
    for i,m in enumerate(starts):out.setdefault(m.group(1),[]).append(text[m.start():starts[i+1].start() if i+1<len(starts) else len(text)])
    return out
def instructions(block):
    out=[]
    for line in block.splitlines():
        m=re.search(r'(0x[0-9a-f]+)\s+@\s*(\d+)\s*:\s*((?:[0-9a-f]{2}\s+)+)(.+)',line)
        if m:out.append(dict(address=m[1],pc=int(m[2]),bytes=m[3].split(),instruction=re.sub(r'0x[0-9a-f]+','ADDR',m[4]).strip()))
    return out
def v8(case,n,filter,richards=False):
    stem=f'{case}.N{n}';p=STORE/'reports'/f'v8.{stem}.log';p.parent.mkdir(parents=True,exist_ok=True)
    base=richards_script(n) if richards else script(case,n,True)
    js=HERE/'scripts/diagnostic'/f'v8.{stem}.js'
    extra=(HERE/'inputs/richards_inspect.js').read_bytes() if richards else b'\n%DebugPrint(microObject);%DebugPrint(sharedProto);%DebugPrint(step);\n'
    save(js,base.read_bytes()+b'\n;\n'+extra)
    help=read(PREV/'raw/build/d8_help.json')['stdout']
    for f in ['print-bytecode','print-bytecode-filter','log-ic','log-maps','log-maps-details','logfile','logfile-per-isolate','allow-natives-syntax']:assert '  --'+f+' ' in help
    cmd=prefixes()['V8_ON']+['--print-bytecode','--print-bytecode-filter='+filter,'--log-ic','--log-maps','--log-maps-details','--no-logfile-per-isolate','--logfile='+str(p),'--allow-natives-syntax',str(js)]
    cached=HERE/'raw/commands'/f'v8_{stem}.json'
    r=read(cached) if cached.exists() else capture('v8_'+stem,cmd,timeout=180)
    assert r['command']==cmd
    assert r['exit_code']==0 and r['stderr'] in ['', 'V8 is running with developer-only features enabled. Stability and security will suffer.\n'] and 'TEB_RESULT:' in r['stdout']
    assert len(r['stdout'])<5000000,'bounded diagnostic dump'
    meta=archive(p,HERE/'raw/diagnostic'/f'v8.{stem}.log.gz');meta.update(binary_sha256=verify()['artifacts']['V8_ON']['sha256'],script_sha256=sha(js),stdout_bytes=len(r['stdout'].encode()),filter=filter);save(HERE/'raw/diagnostic'/f'v8.{stem}.identity.json',meta)
    save(HERE/'bytecode'/f'v8.{stem}.txt',r['stdout'])
    return r['stdout'],p.read_text()
