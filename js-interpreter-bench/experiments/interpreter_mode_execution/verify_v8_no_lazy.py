#!/usr/bin/env python3
"""Evidence gate for the frozen d8 with --max-opt=0 --no-lazy."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
EVIDENCE = HERE / "evidence"
sys.path.insert(0, str(ROOT / "scripts"))
import run_sunspider as baseline  # noqa: E402

LAZY_PROBE = HERE / "probes" / "lazy_order.js"
TIER_PROBE = ROOT / "benchmarks" / "probes" / "v8_tier_probe.js"
MODE_FLAGS = ("--max-opt=0", "--no-lazy")
TRACE_FLAGS = ("--trace-baseline", "--trace-opt", "--trace-opt-status",
               "--trace-deopt", "--trace-osr")


def run(label: str, args: list[str]) -> str:
    command = [str(baseline.V8_BINARY), f"--snapshot_blob={baseline.V8_SNAPSHOT}", *args]
    result = subprocess.run(command, cwd=ROOT, env=baseline.environments()["v8_ignition"],
                            capture_output=True, timeout=120, check=False)
    stdout = baseline.normalize_output(result.stdout)
    stderr = baseline.normalize_output(result.stderr)
    path = EVIDENCE / f"{label}.txt"
    with path.open("x", encoding="utf-8", newline="\n") as f:
        f.write("command=" + " ".join(command) + "\n")
        f.write(f"exit_code={result.returncode}\n--- stdout ---\n{stdout}\n--- stderr ---\n{stderr}\n")
    if result.returncode != 0:
        raise RuntimeError(f"evidence command failed: {path}")
    return stdout


def event_counts(output: str) -> dict[str, int]:
    patterns = {
        "sparkplug_compile": r"\[Baseline batch compilation\]|\[Concurrent Sparkplug",
        "maglev_compile": r"target MAGLEV",
        "turbofan_compile": r"target TURBOFAN",
        "osr_entry": r"\[OSR - entry",
        "baseline_status": r"\bBASELINE\b",
        "maglev_status": r"\^MAGLEV",
        "turbofan_status": r"\^TURBOFAN",
        "interpreted_status": r"INTERPRETED_FUNCTION",
    }
    return {name: len(re.findall(pattern, output)) for name, pattern in patterns.items()}


def main() -> None:
    baseline.verify_frozen_inputs()
    if EVIDENCE.exists():
        raise RuntimeError(f"refusing to overwrite evidence: {EVIDENCE}")
    EVIDENCE.mkdir(parents=True)
    help_text = run("help", ["--help"])
    required_help = ("lazy", "print-bytecode", "print-bytecode-filter", *
                     (flag[2:] for flag in TRACE_FLAGS))
    for flag in required_help:
        if not re.search(rf"(?m)^\s*--{re.escape(flag)}(?:\s|$)", help_text):
            raise RuntimeError(f"current d8 does not expose --{flag}")
    version = run("version", ["--version"])
    if "V8 version 15.6.21" not in version:
        raise RuntimeError("unexpected V8 version")
    flags = run("no_lazy_flag_values", [*MODE_FLAGS, "--print-flag-values", "-e", "0"])
    required_values = ("--max-opt=0", "--no-lazy", "--no-sparkplug",
                       "--no-maglev", "--no-turbofan")
    for value in required_values:
        if not re.search(rf"(?m)^{re.escape(value)}\s*$", flags):
            raise RuntimeError(f"flag value absent: {value}")
    lazy_eval = bool(re.search(r"(?m)^--lazy-eval\s*$", flags))

    ordering: dict[str, str] = {}
    for function in ("workload", "nestedProbe"):
        for name, extra_flags in (("default", ()), ("no_lazy", ("--no-lazy",))):
            output = run(f"lazy_{name}_{function}", ["--max-opt=0", *extra_flags,
                         "--print-bytecode", f"--print-bytecode-filter={function}",
                         str(LAZY_PROBE)])
            marker = output.find("MARKER_BEFORE_TIMER")
            bytecode = output.find(f"generated bytecode for function: {function}")
            after = output.find("MARKER_AFTER_TIMER checksum=5642")
            if min(marker, bytecode, after) < 0 or not marker < after:
                raise RuntimeError(f"lazy ordering markers incomplete: {name}/{function}")
            position = "before_timer" if bytecode < marker else "inside_timer"
            ordering[f"{name}_{function}"] = position
            if name == "default" and position != "inside_timer":
                raise RuntimeError(f"default did not demonstrate lazy compile: {function}")
            if name == "no_lazy" and position != "before_timer":
                raise RuntimeError(f"--no-lazy did not eagerly compile: {function}")

    trace = run("no_lazy_tier_trace", [*MODE_FLAGS, *TRACE_FLAGS,
                                       str(TIER_PROBE), "--", "500000"])
    if "V8_TIER_PROBE iterations=500000 checksum=1301262660" not in trace:
        raise RuntimeError("tier probe checksum differs")
    counts = event_counts(trace)
    if counts["interpreted_status"] < 1 or any(
            count for name, count in counts.items() if name != "interpreted_status"):
        raise RuntimeError(f"tier evidence failed: {counts}")
    bytecode_output = run("no_lazy_tier_bytecode", [*MODE_FLAGS, "--print-bytecode",
                                                   "--print-bytecode-filter=tierProbeTarget",
                                                   str(TIER_PROBE), "--", "500000"])
    if "generated bytecode for function: tierProbeTarget" not in bytecode_output:
        raise RuntimeError("tier probe Ignition bytecode absent")
    summary = {
        "status": "PASS", "v8_version": version.strip(),
        "d8_sha256": baseline.V8_BINARY_SHA256,
        "snapshot_sha256": baseline.V8_SNAPSHOT_SHA256,
        "flags": list(MODE_FLAGS), "lazy_eval_still_enabled": lazy_eval,
        "lazy_ordering": ordering, "tier_events": counts,
        "lazy_probe_sha256": hashlib.sha256(LAZY_PROBE.read_bytes()).hexdigest(),
        "tier_probe_sha256": hashlib.sha256(TIER_PROBE.read_bytes()).hexdigest(),
    }
    with (EVIDENCE / "summary.json").open("x", encoding="utf-8", newline="\n") as f:
        json.dump(summary, f, indent=2)
        f.write("\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
