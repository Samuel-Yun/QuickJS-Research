#!/usr/bin/env python3
"""Check actual generated SunSpider workload bytecode precedes the timer marker."""

from __future__ import annotations

import csv
import gzip
import hashlib
from pathlib import Path
import subprocess

import run_internal as experiment

ROOT = experiment.ROOT
HERE = experiment.HERE
OUTPUT = HERE / "evidence" / "workload_bytecode"
FIELDS = ("test", "status", "exit_code", "bytecode_offset", "timer_marker_offset",
          "completion_marker_offset", "diagnostic_script_sha256", "stdout_sha256",
          "stderr", "stdout_gzip")


def main() -> None:
    expected = experiment.checked_inputs()
    if OUTPUT.exists():
        raise RuntimeError(f"refusing to overwrite {OUTPUT}")
    OUTPUT.mkdir(parents=True)
    records = []
    for test in experiment.baseline.TESTS:
        source = experiment.make_script(test, 1, expected).read_text(encoding="utf-8")
        token = "var timerStart = Date.now();"
        if source.count(token) != 1:
            raise RuntimeError(f"timer marker location ambiguous: {test}")
        diagnostic = source.replace(token, "console.log('MARKER_BEFORE_TIMER');\n" + token, 1)
        script = OUTPUT / f"{test}.diagnostic.js"
        with script.open("x", encoding="utf-8", newline="\n") as f:
            f.write(diagnostic)
        command = experiment.command("v8_ignition", script)
        command[3:3] = ["--print-bytecode", "--print-bytecode-filter=workload"]
        result = subprocess.run(command, cwd=ROOT,
                                env=experiment.baseline.environments()["v8_ignition"],
                                capture_output=True, timeout=120, check=False)
        stdout = experiment.baseline.normalize_output(result.stdout)
        stderr = experiment.baseline.normalize_output(result.stderr)
        bytecode = stdout.find("generated bytecode for function: workload")
        marker = stdout.find("MARKER_BEFORE_TIMER")
        completion = stdout.find("IM_EXEC:")
        valid = (result.returncode == 0 and 0 <= bytecode < marker < completion and
                 f'"test":"{test}"' in stdout[completion:])
        compressed = OUTPUT / f"{test}.stdout.gz"
        with compressed.open("xb") as raw:
            with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as f:
                f.write(result.stdout)
        record = {"test": test, "status": "PASS" if valid else "FAIL",
                  "exit_code": result.returncode, "bytecode_offset": bytecode,
                  "timer_marker_offset": marker, "completion_marker_offset": completion,
                  "diagnostic_script_sha256": hashlib.sha256(script.read_bytes()).hexdigest(),
                  "stdout_sha256": hashlib.sha256(result.stdout).hexdigest(),
                  "stderr": stderr, "stdout_gzip": str(compressed.relative_to(HERE))}
        records.append(record)
        print(f"{test}: {record['status']}", flush=True)
    with (OUTPUT / "summary.csv").open("x", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(records)
    if any(record["status"] != "PASS" for record in records):
        raise RuntimeError("at least one workload bytecode appeared after timer marker")


if __name__ == "__main__":
    main()
