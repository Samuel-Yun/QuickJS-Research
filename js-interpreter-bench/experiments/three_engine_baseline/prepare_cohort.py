def combined(result): return result['stdout'] + '\n' + result['stderr']

def require_success(result):
    if result['exit_code'] != 0:
        raise RuntimeError('diagnostic command failed: ' + str(result['command']))

def v8_counts(text):
    patterns = {'sparkplug_compilation': r'\[Baseline batch compilation\]|\[Concurrent Sparkplug|compiling method.*using Sparkplug',
                'maglev_compilation': r'target MAGLEV', 'turbofan_compilation': r'target TURBOFAN',
                'successful_osr_entry': r'\[OSR - entry', 'baseline_status': r'\bBASELINE\b',
                'maglev_status': r'\^MAGLEV', 'turbofan_status': r'\^TURBOFAN',
                'interpreted_status': r'INTERPRETED_FUNCTION'}
    return {key: len(re.findall(pattern, text, re.I if key.endswith('compilation') else 0)) for key, pattern in patterns.items()}

def tier():
    m = verify()
    probe = HERE / 'probes/tier/hot_probe.js'
    v8base = m['engines']['v8']['command_prefix'][:2]
    help_result = evidence('tier/v8_help', [*v8base, '--help'])
    require_success(help_result)
    help_text = combined(help_result)
    requested = ('--trace-baseline', '--trace-opt', '--trace-opt-status', '--trace-deopt', '--trace-osr', '--print-bytecode')
    supported = {f: bool(re.search(r'^\s*' + re.escape(f) + r'(?:\s|$)', help_text, re.M)) for f in requested}
    if not all(supported.values()):
        save(HERE / 'probes/tier/v8_supported.json', supported)
        raise RuntimeError('required trace unavailable; do not assume tier evidence')
    traces = requested[:-1]
    values = evidence('tier/v8_candidate_flags', [*m['engines']['v8']['command_prefix'], '--print-flag-values'])
    require_success(values)
    flag_text = combined(values)
    required_values = ['--max-opt=0', '--no-sparkplug', '--no-maglev', '--no-turbofan', '--no-lazy']
    effective = {f: bool(re.search(r'^' + re.escape(f) + r'\s*$', flag_text, re.M)) for f in required_values}
    v8_runs = {}
    for mode, default in [('default', True), ('candidate', False)]:
        result = evidence('tier/v8_' + mode, command('v8', probe, traces, default))
        require_success(result)
        if 'TEB_HOT_PASS:500000:1301262660' not in result['stdout']:
            raise RuntimeError('hot probe checksum differs')
        v8_runs[mode] = v8_counts(combined(result))
    bytecode = evidence('tier/v8_candidate_bytecode', command('v8', probe, ('--print-bytecode', '--print-bytecode-filter=__tebHotTarget')))
    require_success(bytecode)
    v8_ignition_bytecode = '[generated bytecode for function: __tebHotTarget' in combined(bytecode)
    v8_pass = all(effective.values()) and v8_ignition_bytecode and (
        sum(v8_runs['default'][key] for key in ('sparkplug_compilation', 'maglev_compilation', 'turbofan_compilation', 'successful_osr_entry')) > 0
        and v8_runs['candidate']['interpreted_status'] > 0
        and all(v8_runs['candidate'][key] == 0 for key in ('sparkplug_compilation', 'maglev_compilation', 'turbofan_compilation', 'successful_osr_entry', 'baseline_status', 'maglev_status', 'turbofan_status')))
    jsc_options = {}
    for mode, prefix in [('default', [m['engines']['jsc']['binary']['path']]), ('candidate', m['engines']['jsc']['command_prefix'])]:
        result = evidence('tier/jsc_' + mode + '_options', [*prefix, '--options'])
        require_success(result)
        options = {}
        for key in ('useLLInt', 'useJIT', 'useBaselineJIT', 'useDFGJIT', 'useFTLJIT', 'useRegExpJIT', 'useLLIntICs', 'reportBytecodeCompileTimes', 'reportBytecodeCacheDecodeTimes'):
            match = re.search(r'^\s*' + key + r'=(true|false)', combined(result), re.M)
            options[key] = match.group(1) == 'true' if match else None
        jsc_options[mode] = options
    jsc_runs = {}
    for mode, default in [('default', True), ('candidate', False)]:
        flags = ('--verboseCompilation=true', '--verboseOSR=true', '--logCompilationChanges=true')
        result = evidence('tier/jsc_' + mode, command('jsc', probe, flags, default))
        require_success(result)
        if 'TEB_HOT_PASS:500000:1301262660' not in result['stdout']:
            raise RuntimeError('JSC hot checksum differs')
        text = result['stderr']
        jsc_runs[mode] = {
            'baseline_compilation': len(re.findall('JIT compilation successful', text)),
            'dfg_code_events': len(re.findall(r'Installing .*DFG', text)),
            'ftl_code_events': len(re.findall(r'Installing .*FTL', text)),
            'successful_osr': len(re.findall(r'Performing OSR', text)),
            'llint_installations': len(re.findall(r'Installing .*LLInt', text)),
            'osr_slowpath_entries': len(re.findall(r'Entered (?:entry_osr|loop_osr)', text))}
    opts = jsc_options['candidate']
    jsc_pass = opts['useLLInt'] is True and all(opts[key] is False for key in ('useJIT', 'useBaselineJIT', 'useDFGJIT', 'useFTLJIT')) and (
        jsc_runs['default']['baseline_compilation'] > 0
        and jsc_runs['candidate']['llint_installations'] > 0
        and all(jsc_runs['candidate'][key] == 0 for key in ('baseline_compilation', 'dfg_code_events', 'ftl_code_events', 'successful_osr')))
    qjs = m['engines']['quickjs']['binary']['path']
    qsource = Path(qjs).parent
    macros = capture(['gcc', '-D_GNU_SOURCE', '-DCONFIG_VERSION="2026-06-04"', '-DHAVE_CLOSEFROM', '-O2', '-dM', '-E', 'quickjs.c'], qsource)
    save(HERE / 'probes/tier/quickjs_macros.txt', macros['stdout'])
    symbols = capture(['nm', '-a', qjs])
    save(HERE / 'probes/tier/quickjs_symbols.txt', symbols['stdout'])
    disasm = capture(['objdump', '-d', '-Mintel', '--disassemble=JS_CallInternal', qjs])
    save(HERE / 'probes/tier/quickjs_JS_CallInternal.txt', disasm['stdout'])
    indexed_jumps = re.findall(r'^.*\bjmp\s+QWORD PTR \[[^\n]*\*8[^\n]*$', disasm['stdout'], re.M)
    dispatch_lines = [line for line in symbols['stdout'].splitlines() if 'dispatch_table' in line]
    qjs_result = evidence('tier/quickjs_hot', command('quickjs', probe))
    require_success(qjs_result)
    qjs_pass = '#define DIRECT_DISPATCH 1' in macros['stdout'] and bool(dispatch_lines) and bool(indexed_jumps) and 'TEB_HOT_PASS:500000:1301262660' in qjs_result['stdout']
    summary = {'v8': {'pass': v8_pass, 'trace_supported': supported, 'effective_flags': effective, 'counts': v8_runs,
                       'ignition_bytecode_observed': v8_ignition_bytecode,
                       'regexp_interpret_all': bool(re.search(r'^--regexp-interpret-all\s*$', flag_text, re.M)),
                       'bytecode_flushing_enabled': bool(re.search(r'^--flush-bytecode\s*$', flag_text, re.M))},
               'jsc': {'pass': jsc_pass, 'options': jsc_options, 'counts': jsc_runs,
                       'osr_slowpath_is_successful_osr': False},
               'quickjs': {'pass': qjs_pass, 'direct_dispatch_macro': '#define DIRECT_DISPATCH 1' in macros['stdout'],
                           'dispatch_table_symbols': dispatch_lines, 'indexed_indirect_jumps': indexed_jumps[:12]},
               'all_mode_gates_pass': qjs_pass and v8_pass and jsc_pass}
    save(HERE / 'probes/tier/summary.json', summary)
    print('Tier gates: ' + str(summary['all_mode_gates_pass']), flush=True)

def frontend():
    verify()
    static = HERE / 'probes/frontend_order/static_probe.js'
    results = {}
    for label, engine, flags, default in [
        ('v8_default', 'v8', ('--print-bytecode', '--print-bytecode-filter=__tebStatic*'), True),
        ('v8_no_lazy', 'v8', ('--print-bytecode', '--print-bytecode-filter=__tebStatic*'), False),
        ('jsc_source', 'jsc', ('--reportBytecodeCompileTimes=true', '--dumpGeneratedBytecodes=true'), False)]:
        result = evidence('frontend_order/' + label, command(engine, static, flags, default))
        require_success(result)
        text = result['stderr'] if engine == 'jsc' else result['stdout']
        start = re.search(r'^TEB_TIMER_START\s*$', text, re.M)
        stop = re.search(r'^TEB_TIMER_STOP\s*$', text, re.M)
        result_summary = {'timer_markers_seen': bool(start and stop)}
        for target in ('__tebStaticWorkload', '__tebStaticChild'):
            if engine == 'v8':
                dump = re.search(r'\[generated bytecode for function: ' + target + r'\b', text)
                result_summary[target] = {'bytecode_before_marker': bool(start and dump and dump.start() < start.start())}
            else:
                dump = re.search(re.escape(target) + r'#([^:]+):', text)
                compile_event = re.search('Compiled #' + re.escape(dump.group(1)) + r' into bytecode', text) if dump else None
                result_summary[target] = {'code_hash': dump.group(1) if dump else None,
                    'generation_event_seen': bool(compile_event),
                    'generation_before_marker': bool(start and compile_event and compile_event.start() < start.start()) if compile_event else None,
                    'generation_inside_region': bool(start and stop and compile_event and start.start() < compile_event.start() < stop.start()) if compile_event else None}
        results[label] = result_summary
    actual = []
    for benchmark, cases in [('SunSpider', SUNSPIDER), ('Octane', OCTANE)]:
        for case in cases:
            script = generate(benchmark, case, 1, 'frontend')
            target = '__tebSunSpiderWorkload' if benchmark == 'SunSpider' else OCTANE[case][3]
            for engine in ('v8', 'jsc'):
                flags = ('--print-bytecode', '--print-bytecode-filter=' + target) if engine == 'v8' else ('--reportBytecodeCompileTimes=true', '--dumpGeneratedBytecodes=true')
                result = evidence('frontend_order/actual_' + benchmark + '_' + case + '_' + engine, command(engine, script, flags))
                require_success(result)
                text = result['stderr'] if engine == 'jsc' else result['stdout']
                marker = re.search(r'^TEB_TIMER_START(?:[:\n]|$)', text, re.M)
                item = {'benchmark': benchmark, 'case': case, 'engine': engine, 'target': target,
                        'script_sha256': sha(script), 'timer_marker_seen': bool(marker)}
                if engine == 'v8':
                    match = re.search(r'\[generated bytecode for function: ' + target + r'\b', text)
                    item['primary_run_bytecode_before_marker'] = bool(marker and match and match.start() < marker.start()) if match else None
                else:
                    match = re.search(re.escape(target) + r'#([^:]+):', text)
                    generation = re.search('Compiled #' + re.escape(match.group(1)) + ' into bytecode', text) if match else None
                    item.update(code_hash=match.group(1) if match else None,
                        primary_run_generation_event_seen=bool(generation),
                        primary_run_generation_before_marker=bool(marker and generation and generation.start() < marker.start()) if generation else None)
                actual.append(item)
    old = ROOT / 'experiments/jsc_baseline/probes/frontend_order'
    results['phase1_cache_evidence_rechecked'] = {name: sha(old / name) for name in ('cache_prepare.stderr.txt', 'cache_consume.stderr.txt', 'static_function.stderr.txt')}
    results['actual_selected_workloads'] = actual
    results['static_frontend_exclusion_guaranteed'] = False
    results['prepare_mechanism_without_workload_execution'] = None
    results['investigation_budget_minutes'] = 90
    save(HERE / 'probes/frontend_order/summary.json', results)
    print('Frontend ordering recorded; MAIN remains first-call-inclusive', flush=True)

def timer():
    verify()
    summary = {}
    for engine in ENGINES:
        result = evidence('timer/' + engine, command(engine, HERE / 'probes/timer/timer_probe.js'))
        require_success(result)
        match = re.search(r'^TEB_TIMER:(.+)$', result['stdout'], re.M)
        summary[engine] = json.loads(match.group(1)) if match else None
    save(HERE / 'probes/timer/summary.json', summary)
    # Verify the MAIN loop without diagnostics on one explicit case, not a campaign.
    script = generate('SunSpider', 'bitops-bitwise-and', 16, 'main')
    for engine in ENGINES:
        result = evidence('timer/main_smoke_' + engine, command(engine, script))
        validated_payload(result, 'SunSpider', 'bitops-bitwise-and', 16, 'main')
    print('Common Date.now and untraced MAIN smoke verified', flush=True)

def correctness():
    verify()
    rows = []
    for benchmark, cases in [('SunSpider', SUNSPIDER), ('Octane', OCTANE)]:
        for case in cases:
            for n in (1, 2, 16):
                script = generate(benchmark, case, n, 'correctness')
                for engine in ENGINES:
                    result = evidence(f'correctness/{benchmark}_{case}_N{n}_{engine}', command(engine, script))
                    status, reason, payload = 'PASS', '', {}
                    try:
                        payload = validated_payload(result, benchmark, case, n, 'correctness')
                    except (ValueError, KeyError, TypeError) as error:
                        status = 'TIMEOUT' if result.get('timeout') else 'FAIL'
                        reason = str(error)
                    rows.append({'benchmark': benchmark, 'case': case, 'engine': engine, 'N': n,
                                 'status': status, 'reason': reason, 'exit_code': result['exit_code'],
                                 'checksum': payload.get('checksum'), 'extra_validation_calls': payload.get('extra_validation_calls', 0),
                                 'warmup_calls': payload.get('warmup_calls'), 'script_sha256': sha(script),
                                 'command': json.dumps(result['command']),
                                 'stdout_path': f'probes/correctness/{benchmark}_{case}_N{n}_{engine}/stdout.txt',
                                 'stderr_path': f'probes/correctness/{benchmark}_{case}_N{n}_{engine}/stderr.txt'})
                print(f'{benchmark}/{case} N={n}: ' + ', '.join(engine + '=' + rows[-3 + i]['status'] for i, engine in enumerate(ENGINES)), flush=True)
    content = io.StringIO(newline='')
    writer = csv.DictWriter(content, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)
    save(HERE / 'probes/correctness/results.csv', content.getvalue())
    save(HERE / 'probes/correctness/summary.json', {'expected': 72, 'actual': len(rows),
        'pass': sum(row['status'] == 'PASS' for row in rows), 'all_pass': len(rows) == 72 and all(row['status'] == 'PASS' for row in rows)})

def audit():
    m = verify()
    tier_results = json.loads((HERE / 'probes/tier/summary.json').read_text())
    front = json.loads((HERE / 'probes/frontend_order/summary.json').read_text())
    timers = json.loads((HERE / 'probes/timer/summary.json').read_text())
    correct = json.loads((HERE / 'probes/correctness/summary.json').read_text())
    timers_valid = all(timers[e] and timers[e]['date_available'] and timers[e]['date']['changes'] > 0 for e in ENGINES)
    ready = tier_results['all_mode_gates_pass'] and timers_valid and correct['all_pass']
    output = {'status': 'READY_FIRST_CALL_INCLUSIVE' if ready else 'BLOCKED_VALIDATION',
        'cohort_id': m['cohort_id'], 'platform': 'WSL2 Ubuntu 24.04.2 x86_64',
        'same_host_os_architecture': True, 'old_windows_results_comparable': False,
        'runtime_hashes_verified': True, 'execution_mode_gates': tier_results,
        'main_metric': 'first-call-inclusive interpreter-mode execution time',
        'no_performance_warmup': True, 'static_frontend_exclusion': 'UNKNOWN',
        'frontend_prepared_no_warmup_ready': False, 'timer': timers, 'correctness': correct,
        'old_baseline_and_data_preserved': True, 'formal_samples_taken': 0,
        'full_suite_compatibility': None, 'future_full_formal_run_authorized': False,
        'v8_exact_artifact_source_commit': None, 'v8_exact_compiler_revision': None,
        'binary_sha256': {e: m['engines'][e]['binary']['sha256'] for e in ENGINES},
        'manifest_sha256': sha(HERE / 'manifest.json'), 'input_manifest_sha256': sha(HERE / 'input_manifest.json'),
        'execution_contract_sha256': sha(HERE / 'execution_contract.json')}
    save(HERE / 'summary/audit.json', output)
    save(HERE / 'preservation_after.json', json.loads((HERE / 'preservation_before.json').read_text()))
    print(output['status'], flush=True)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('stage', choices=['freeze', 'tier', 'frontend', 'timer', 'correctness', 'audit', 'verify'])
    args = parser.parse_args()
    if args.stage == 'freeze':
        freeze_inputs(); verify(); print('inputs frozen')
    elif args.stage == 'tier': tier()
    elif args.stage == 'frontend': frontend()
    elif args.stage == 'timer': timer()
    elif args.stage == 'correctness': correctness()
    elif args.stage == 'audit': audit()
    else: verify(); print('runtime, dependency, workload, harness and old-data hashes verified')

if __name__ == '__main__': main()
