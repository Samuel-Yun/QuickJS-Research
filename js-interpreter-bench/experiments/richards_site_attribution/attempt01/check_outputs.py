"""Final report/code cross-check, never edits raw evidence."""
import hashlib
import re
import run as r
import analyze as a
H=r.HERE

def main():
    q=r.read(H/'bytecode/quickjs/TaskControlBlock.prototype.isHeldOrSuspended.decoded.json')
    v=r.read(H/'bytecode/v8/TaskControlBlock.isHeldOrSuspended.decoded.json')
    assert len(q)==16 and sum(x['size'] for x in q)==29
    assert len(v)==14 and sum(x['size'] for x in v)==31
    # Diagnostic print/log flags must not silently change selected bytecodes.
    text=(H/'bytecode/v8.full.txt').read_text()
    start=re.search(r'(?m)^\[generated bytecode for function: TaskControlBlock.isHeldOrSuspended \(',text);assert start
    end=re.search(r'(?m)^\[generated bytecode for function:',text[start.end():])
    block=text[start.start():start.end()+end.start()]
    actual=[]
    for line in block.splitlines():
        m=re.search(r'@\s*(\d+)\s*:\s*((?:[0-9a-f]{2}\s+)+)([A-Z]\w*)(.*)$',line)
        if m:actual.append((int(m[1]),len(m[2].split()),m[3],m[4].strip()))
    norm=lambda op:re.sub(r'0x[0-9a-f]+','<address>',op)
    assert [(off,size,name,norm(op)) for off,size,name,op in actual]==[(x['offset'],x['size'],x['opcode'],norm(x['operands'])) for x in v]
    # Sampler builds never have full counting on in sampled runs.
    for path in (H/'raw').glob('sample_*.settings.json'):
        x=r.read(path);assert x['count']==0 and x['binary_sha256']==r.sha(r.BUILD/'qjs')
        meta=dict(line.split('=') for line in path.with_name(path.name.replace('.settings.json','.meta.txt')).read_text().splitlines())
        assert meta['dropped']=='0'
    # Full identity/metadata, not a native pointer or function name alone.
    target='TaskControlBlock.prototype.isHeldOrSuspended'
    keys=[]
    for label in ('counts_N1','counts_N2','sample_ctx1_rep1','sample_ctx1_rep2','sample_ctx1_rep3','sample_ctx1_20ms'):
        funcs,sites=a.identity(label)
        x=[s for s in sites.values() if s['function']==target and s['offset']==3]
        assert len(x)==1;keys.append(x[0]['site_key'])
    assert len(set(keys))==1
    r.save(H/'summary/selected_bytecode_checks.json',dict(status='PASS',
       quickjs=dict(instructions=len(q),bytes=29),v8=dict(instructions=len(v),bytes=31),
       v8_original_vs_logged_dump_same_instructions=True,selected_QJS_site_key_cross_process_equal=True,
       sampled_runs_detailed_counting_off=True))
    r.audit_preservation()
    assert r.read(H/'summary/audit.json')['formal_new_samples']==0
    # Repository-side diagnostic source identical to build input, including LF.
    for name in ('site_hooks.h','site_metadata.h'):assert r.sha(H/'probes'/name)==r.sha(r.BUILD/name)
    print('OUTPUT_CHECKS_PASS',flush=True)

if __name__=='__main__':main()
