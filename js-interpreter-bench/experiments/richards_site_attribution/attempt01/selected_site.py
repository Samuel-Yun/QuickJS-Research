"""Selected original Richards site: actual dump/IC-log address join, not an IC hit count."""
import collections
import csv
import json
import re
import run as r
import analyze as a
HERE,ROOT,save,read,export=r.HERE,r.ROOT,r.save,r.read,r.export

def main():
    text=(HERE/'bytecode/v8_selected_site_full.same_process.txt').read_text()
    name='TaskControlBlock.isHeldOrSuspended'
    start=re.search(r'(?m)^\[generated bytecode for function: '+re.escape(name)+r' \(',text);assert start
    end=re.search(r'(?m)^\[generated bytecode for function:',text[start.end():])
    block=text[start.start():start.end()+end.start()] if end else text[start.start():]
    save(HERE/'bytecode/v8'/(name+'.txt'),block)
    ins=[]
    for line in block.splitlines():
        m=re.search(r'(0x[0-9a-f]+)\s+@\s*(\d+)\s*:\s*((?:[0-9a-f]{2}\s+)+)([A-Z]\w*)(.*)$',line)
        if m:ins.append(dict(address=m[1],offset=int(m[2]),size=len(m[3].split()),opcode=m[4],operands=m[5].strip()))
    length=int(re.search(r'Bytecode length: (\d+)',block)[1]);assert sum(i['size'] for i in ins)==length==31
    assert ins[0]['opcode']=='GetNamedProperty' and ins[0]['offset']==0
    save(HERE/'bytecode/v8'/(name+'.decoded.json'),ins)
    at={int(i['address'],16):i for i in ins};transitions=[]
    with (HERE/'raw/v8_selected_site_full.log').open(newline='') as f:
        for row in csv.reader(f):
            if row and row[0]=='LoadIC' and int(row[1],16) in at:
                i=at[int(row[1],16)]
                transitions.append(dict(event=row[0],address=row[1],bytecode_offset=i['offset'],opcode=i['opcode'],
                    generated_line=int(row[3]),column=int(row[4]),old_state_code=row[5],new_state_code=row[6],
                    receiver_map=row[7],property=row[8],raw_record=row))
    assert {t['bytecode_offset'] for t in transitions}=={0,19}
    assert len(transitions)==2 and all(t['property']=='state' and t['old_state_code']=='0' and t['new_state_code']=='1' for t in transitions)
    export(HERE/'mapping/v8_selected_IC_transitions.csv',transitions)
    save(HERE/'summary/v8_selected_site.json',dict(status='ACTUAL_SAME_PROCESS_BYTECODE_AND_IC_TRANSITIONS',
        N=32,transitions=transitions,no_later_transition_in_this_log=True,
        hit_count=None,miss_count=None,hit_rate=None,executed_handler_branch=None,
        exact_source_commit=None,state_code_interpretation='raw actual log codes retained; no artifact-source attestation',
        DebugPrint='short JSFunction identity only; no feedback-vector detail in this artifact'))
    # Preserve the same-hash artifact handler evidence, not a nearby-source substitute.
    prior=ROOT/'experiments/bytecode_whitebox_simple/attempt01'
    p=prior/'bytecode/v8_native/GetNamedProperty.disassembly.txt'
    save(HERE/'source_evidence/v8_GetNamedProperty.actual.disassembly.txt',p.read_bytes())
    mapping=read(prior/'source_evidence/v8_native_map.json')
    assert mapping['binary_sha256']==read(HERE/'manifest.json')['engines']['v8']['binary']['sha256']
    save(HERE/'source_evidence/reused_v8_handler_identity.json',dict(original_path=str(p.relative_to(ROOT)),sha256=r.sha(p),mapping=mapping,
        evidence='same frozen binary ELF bytes and previous actual loaded code map; existence is not selected-site branch execution proof'))
    # Small frozen-binary controls quantify total diagnostic-build perturbation.
    p=HERE/'scripts/original.N512.js'
    for rep in range(1,4):
        rr=r.capture(HERE/'raw'/f'control_frozen_nosignal_rep{rep}.json',r.command('quickjs',p));r.check(rr)
    rows=a.rows(HERE/'summary/site_samples.csv')
    for field in ('function','property','operation'):
        d=collections.defaultdict(lambda:collections.Counter())
        for x in rows:
            for k in ('lookup_samples','other_context_samples','ops_per_Run','probes_per_Run'):d[x[field]][k]+=int(x[k])
        out=[dict(group=k,**v) for k,v in sorted(d.items(),key=lambda kv:-kv[1]['lookup_samples'])]
        export(HERE/'summary'/f'samples_by_{field}.csv',out)
    # Machine-code snippets show publication before lookup and clearing before dispatch.
    asm=(HERE/'source_evidence/JS_CallInternal.diagnostic.disassembly.txt').read_text().splitlines()
    hits=[i for i,line in enumerate(asm) if 'call ' in line and '<sa_begin>' in line]
    save(HERE/'source_evidence/context_boundaries.disassembly.txt',
         '\n\n'.join('\n'.join(asm[max(0,i-12):i+155]) for i in hits))
    print('SELECTED_SITE_DUMPS_AND_IC_ADDRESS_JOIN_PASS',flush=True)

if __name__=='__main__':main()
